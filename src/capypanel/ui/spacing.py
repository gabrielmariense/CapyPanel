"""One spacing scale for every screen, each size with one job. A layout that sets a gap or a
margin uses one of these; a few px inside a small part (a row's own padding, a chip) are that
part's business and stay where they're drawn."""

ICON = 4  # between an icon and its word, and between small things that belong together
CONTROLS = 8  # between controls on a line
PANEL = 12  # inside a panel or a card
WINDOW = 16  # around a window, and between sections
