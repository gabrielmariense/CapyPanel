"""Writes every built-in theme's colour roles to a Markdown file, from the code itself.
Run from the repo: uv run --no-sync python scripts/colour_roles.py <output.md>"""

import sys
from pathlib import Path

from capypanel.ui.themes import engine

# What each role is for (not in the code). A role missing here shows "(no use line)".
USE = {
    "bg": "window background behind the panels",
    "card": "panels and cards",
    "raised": "toolbar buttons, button hover, disabled fields, alternate rows",
    "border": "frames, fields, dividers",
    "chrome": "menu bar, the rail, status bar",
    "text": "main text",
    "text2": "secondary text, labels",
    "text3": 'hints, "not checked", the quietest text',
    "hover": "menu and tool-button hover (with alpha)",
    "sel_solid": "the picked row",
    "accent": "section headings, the picked item, the main button",
    "accent_hover": "the main button under the pointer",
    "online": "status: answers, fine",
    "offline": "status: doesn't answer, or never checked",
    "attention": "amber: deletes, risky, needs attention",
    "stopped": "status: a problem",
    "working": "status: in use, at work",
    "ink_black": "supply bar: black toner",
    "ink_cyan": "supply bar: cyan",
    "ink_magenta": "supply bar: magenta",
    "ink_yellow": "supply bar: yellow",
    "ink_yellow_edge": "the 1 px edge around yellow",
    "ink_other": "supply bar: drum, waste box, fuser",
}


def themes() -> list[tuple[str, dict[str, str]]]:
    out = [
        ("CapyPanel dark", dict(engine.TOKENS["dark"])),
        ("CapyPanel light", dict(engine.TOKENS["light"])),
    ]
    for name in ("graphite", "paper"):
        theme = engine.load_theme_file(engine.THEMES_DIR / f"{name}.json")
        out.append((theme.title(), dict(theme.colors)))
    for scheme in ("dark", "light"):
        native = dict(engine.NATIVE_TOKENS[scheme])
        for key in engine.STATUS_KEYS:  # fitted at run time to Windows' accent selection
            native.setdefault(key, f"~{engine.TOKENS[scheme][key]}")
        for key in engine.INK_KEYS:
            native.setdefault(key, engine.TOKENS[scheme][key])
        out.append((f"Windows {scheme}", native))
    return out


def main() -> None:
    out_path = Path(sys.argv[1])
    columns = themes()
    roles = list(dict.fromkeys(k for _, colors in columns for k in colors))
    lines = [
        "# CapyPanel colour roles",
        "",
        "Generated by colour_roles.py from engine.py (TOKENS, NATIVE_TOKENS) and the shipped theme "
        'files. Don\'t edit by hand: run it again when a theme changes. "~" marks a Windows '
        "theme's status colour, which is fitted at run time to Windows' accent; an empty cell is "
        "drawn by Windows itself. Windows follow-system uses the dark or light column.",
        "",
        "| Role | Use | " + " | ".join(name for name, _ in columns) + " |",
        "|---|---|" + "---|" * len(columns),
    ]
    for role in roles:
        cells = [colors.get(role, "") for _, colors in columns]
        lines.append(f"| {role} | {USE.get(role, '(no use line)')} | " + " | ".join(cells) + " |")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(roles)} roles, {len(columns)} themes -> {out_path}")


if __name__ == "__main__":
    main()
